USE pharmacy;

-- Workbench по умолчанию запрещает UPDATE/DELETE без условия по ключу
-- (Safe Updates). Отключаем на время сессии:
SET SQL_SAFE_UPDATES = 0;


-- =====================================================================
-- БЛОК 1. ДОБАВЛЕНИЕ, ОБНОВЛЕНИЕ, УДАЛЕНИЕ (DML) + ИЗМЕНЕНИЕ СТРУКТУРЫ (DDL)
-- =====================================================================

-- 1. Зарегистрировать нового клиента при первом обращении
INSERT INTO клиент (Имя, Номер_телефона)
VALUES ('Вероника', '+7 916 123-45-67');

-- проверка
SELECT * FROM клиент WHERE Номер_телефона = '+7 916 123-45-67';

-- 2. Аптека «Фармлайн №3» перешла на круглосуточный режим работы
UPDATE аптека
SET График = 'круглосуточно'
WHERE Название_аптеки = 'Фармлайн №3';

-- 3. Индексация: повысить на 5 % цены в аптеке с ID = 1
--    (в транзакции: смотрим результат и откатываем, чтобы цены не росли
--     при каждом повторном запуске; для сохранения — COMMIT вместо ROLLBACK)
START TRANSACTION;
UPDATE ассортимент
SET Цена_за_упаковку = ROUND(Цена_за_упаковку * 1.05, 2)
WHERE ID_Аптека = 1;
SELECT * FROM ассортимент WHERE ID_Аптека = 1;
ROLLBACK;

-- 4. Клиент отозвал согласие на хранение данных — удалить его
DELETE FROM клиент
WHERE Номер_телефона = '+7 916 123-45-67';

-- 5. (DDL) Добавить клиентам e-mail для уведомлений о поступлении лекарств
ALTER TABLE клиент ADD COLUMN Email VARCHAR(100) NULL;
-- откат (чтобы структура осталась прежней):
ALTER TABLE клиент DROP COLUMN Email;


-- =====================================================================
-- БЛОК 2. ИЗВЛЕЧЕНИЕ ИЗ ОДНОЙ ТАБЛИЦЫ
-- =====================================================================

-- 6. Клиент ищет аптеку, открытую ночью
SELECT Название_аптеки, Адрес
FROM аптека
WHERE График = 'круглосуточно';

-- 7. Оператор ищет лекарство по части названия («ибупрофен»)
SELECT ID, Название_лекарства
FROM лекарство
WHERE Название_лекарства LIKE '%ибупрофен%'
ORDER BY Название_лекарства;

-- 8. 10 самых дорогих позиций в диапазоне 1000–3000 руб.
SELECT ID_Аптека, ID_Лекарство, Цена_за_упаковку
FROM ассортимент
WHERE Цена_за_упаковку BETWEEN 1000 AND 3000
ORDER BY Цена_за_упаковку DESC
LIMIT 10;


-- =====================================================================
-- БЛОК 3. ИЗВЛЕЧЕНИЕ ИЗ СВЯЗАННЫХ ТАБЛИЦ (JOIN)
-- =====================================================================

-- 9. Справочник аптек для оператора: сеть, район, график (3 таблицы)
SELECT а.Название_аптеки, с.Наименование_сети, р.Название_района, а.График
FROM аптека а
JOIN сеть   с ON с.ID = а.ID_Сеть
JOIN районы р ON р.ID = а.ID_Районы
ORDER BY с.Наименование_сети, а.Название_аптеки;

-- 10. Где купить «Азитромицин»: аптеки, где он в наличии, от дешёвых к дорогим
--     (4 таблицы)
SELECT л.Название_лекарства, а.Название_аптеки, ф.Название AS Форма,
       асс.Цена_за_упаковку, асс.Количество_в_аптеке
FROM ассортимент асс
JOIN лекарство л         ON л.ID = асс.ID_Лекарство
JOIN аптека а            ON а.ID = асс.ID_Аптека
JOIN `форма выпуска` ф   ON ф.ID = асс.ID_Форма_выпуска
WHERE л.Название_лекарства LIKE 'Азитромицин%'
  AND асс.Количество_в_аптеке > 0
ORDER BY асс.Цена_за_упаковку;

-- 11. Журнал последних обращений: кто, что, в какой аптеке, когда (4 таблицы)
SELECT к.Имя, к.Номер_телефона, л.Название_лекарства, а.Название_аптеки,
       з.Дата_запроса, з.Запрашиваемое_количество
FROM `запросы на лекарства` з
JOIN клиент к    ON к.ID = з.ID_Клиент
JOIN лекарство л ON л.ID = з.ID_Лекарство
JOIN аптека а    ON а.ID = з.ID_Аптека
ORDER BY з.Дата_запроса DESC
LIMIT 20;

-- 12. Как добраться до аптеки: транспорт, номер маршрута, остановка (5 таблиц)
SELECT а.Название_аптеки, вт.Название AS Транспорт,
       тм.Номер_маршрута, о.Название_остановки
FROM аптека а
JOIN `маршруты аптек` ма        ON ма.ID_Аптека = а.ID
JOIN `транспортные маршруты` тм ON тм.ID = ма.ID_Транспортный_маршрут
JOIN `вид транспорта` вт        ON вт.ID = тм.ID_Вид_транспорта
JOIN остановка о                ON о.ID = тм.ID_Остановка
ORDER BY а.Название_аптеки, вт.Название;


-- =====================================================================
-- БЛОК 4. АГРЕГИРУЮЩИЕ (ИТОГОВЫЕ) ФУНКЦИИ
-- =====================================================================

-- 13. Сколько аптек в каждой сети
SELECT с.Наименование_сети, COUNT(а.ID) AS Количество_аптек
FROM сеть с
LEFT JOIN аптека а ON а.ID_Сеть = с.ID
GROUP BY с.ID, с.Наименование_сети
ORDER BY Количество_аптек DESC;

-- 14. Ценовая политика: мин., средняя и макс. цена по группам лекарств
SELECT н.Наименование_Назначения,
       COUNT(*)                           AS Позиций,
       MIN(асс.Цена_за_упаковку)          AS Мин_цена,
       ROUND(AVG(асс.Цена_за_упаковку),2) AS Средняя_цена,
       MAX(асс.Цена_за_упаковку)          AS Макс_цена
FROM ассортимент асс
JOIN лекарство л  ON л.ID = асс.ID_Лекарство
JOIN назначение н ON н.ID = л.ID_Назначение
GROUP BY н.ID, н.Наименование_Назначения
ORDER BY Средняя_цена DESC;

-- 15. Кандидаты в программу лояльности: клиенты с 12 и более обращениями
SELECT к.Имя, к.Номер_телефона, COUNT(*) AS Запросов, SUM(з.Покупка) AS Покупок
FROM `запросы на лекарства` з
JOIN клиент к ON к.ID = з.ID_Клиент
GROUP BY к.ID, к.Имя, к.Номер_телефона
HAVING COUNT(*) >= 12
ORDER BY Запросов DESC;


-- =====================================================================
-- БЛОК 5. НЕТРИВИАЛЬНЫЕ ЗАПРОСЫ (даты, строки)
-- =====================================================================

-- 16. Даты: статистика обращений по месяцам и среднее ожидание покупки в днях
SELECT DATE_FORMAT(Дата_запроса, '%Y-%m')                AS Месяц,
       COUNT(*)                                           AS Запросов,
       SUM(Покупка)                                       AS Выкуплено,
       ROUND(AVG(DATEDIFF(Дата_покупки, Дата_запроса)),1) AS Среднее_ожидание_дней
FROM `запросы на лекарства`
GROUP BY DATE_FORMAT(Дата_запроса, '%Y-%m')
ORDER BY Месяц;

-- 17. Строки: список для SMS-рассылки — имя заглавными, телефон без пробелов
--     и дефисов, готовый текст сообщения
SELECT UPPER(Имя)                                         AS Имя,
       REPLACE(REPLACE(Номер_телефона, ' ', ''), '-', '') AS Телефон,
       CONCAT(Имя, ', ваш заказ готов к выдаче!')         AS Текст_SMS
FROM клиент
ORDER BY Имя;


-- =====================================================================
-- БЛОК 6. ЗАПРОСЫ С ПОДЗАПРОСАМИ (SELECT, DML, DDL)
-- =====================================================================

-- 18. Позиции дороже средней цены по всей сети
SELECT л.Название_лекарства, асс.Цена_за_упаковку
FROM ассортимент асс
JOIN лекарство л ON л.ID = асс.ID_Лекарство
WHERE асс.Цена_за_упаковку > (SELECT AVG(Цена_за_упаковку) FROM ассортимент)
ORDER BY асс.Цена_за_упаковку DESC
LIMIT 15;

-- 19. Лекарства из справочника, которых нет ни в одной аптеке
--     (кандидаты на закупку), NOT EXISTS
SELECT л.Название_лекарства, н.Наименование_Назначения
FROM лекарство л
JOIN назначение н ON н.ID = л.ID_Назначение
WHERE NOT EXISTS (
    SELECT 1 FROM ассортимент асс
    WHERE асс.ID_Лекарство = л.ID
)
ORDER BY н.Наименование_Назначения, л.Название_лекарства;

-- 20. (DML с подзапросом) Скидка 10 % на лекарства, которые ни разу не запрашивали
--     (в транзакции, как запрос 3)
START TRANSACTION;
UPDATE ассортимент
SET Цена_за_упаковку = ROUND(Цена_за_упаковку * 0.9, 2)
WHERE ID_Лекарство NOT IN (
    SELECT DISTINCT ID_Лекарство FROM `запросы на лекарства`
);
SELECT COUNT(*) AS Подешевело_позиций FROM ассортимент
WHERE ID_Лекарство NOT IN (SELECT DISTINCT ID_Лекарство FROM `запросы на лекарства`);
ROLLBACK;

-- 21. (DDL с подзапросом) Таблица «популярные лекарства» — топ-10 по обращениям
--     для витрины на сайте
DROP TABLE IF EXISTS популярные_лекарства;
CREATE TABLE популярные_лекарства AS
SELECT л.ID, л.Название_лекарства, COUNT(*) AS Запросов
FROM `запросы на лекарства` з
JOIN лекарство л ON л.ID = з.ID_Лекарство
GROUP BY л.ID, л.Название_лекарства
ORDER BY Запросов DESC
LIMIT 10;

SELECT * FROM популярные_лекарства;

SET SQL_SAFE_UPDATES = 1;
