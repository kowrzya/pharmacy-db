-- Предметная область: «Аптека» (справочная служба сети аптек), база pharmacy
-- Номера запросов совпадают с формулировками из ЛР-2.
-- Запускать по одному: курсор на запрос → Ctrl+Enter.
-- Вернуть базу в исходное состояние: запустить целиком pharmacy_reset.sql.
